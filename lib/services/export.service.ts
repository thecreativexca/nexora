import "server-only";

import { formatMoney } from "@/lib/utils/money";

export interface ExportColumn<T = Record<string, unknown>> {
  header: string;
  key: keyof T | string;
  format?: "text" | "currency" | "number" | "date";
  transform?: (row: T) => string | number;
}

export interface ExportReportOptions<T = Record<string, unknown>> {
  reportTitle: string;
  businessName?: string;
  periodLabel?: string;
  generatedBy?: string;
  generatedAt?: string;
  columns: ExportColumn<T>[];
  data: T[];
  totalsRow?: Record<string, string | number>;
}

/**
 * Sanitizes cell values to prevent CSV / Spreadsheet formula injection.
 * (Prepends single quote if cell starts with =, +, -, @, tab, or carriage return).
 */
export function sanitizeCellForSpreadsheet(val: unknown): string {
  if (val === null || val === undefined) return "";
  const str = String(val);
  if (/^[=+\-@\t\r]/.test(str)) {
    return `'${str}`;
  }
  return str;
}

/**
 * Generates an RFC-4180 compliant CSV string with UTF-8 BOM.
 */
export function generateCsvExport<T extends Record<string, unknown>>(
  options: ExportReportOptions<T>,
): string {
  const lines: string[] = [];

  // Metadata headers
  lines.push(`"${options.businessName ?? "Nexora"} - ${options.reportTitle}"`);
  if (options.periodLabel) {
    lines.push(`"Reporting Period: ${sanitizeCellForSpreadsheet(options.periodLabel)}"`);
  }
  lines.push(`"Generated At: ${options.generatedAt ?? new Date().toISOString()}"`);
  if (options.generatedBy) {
    lines.push(`"Generated By: ${sanitizeCellForSpreadsheet(options.generatedBy)}"`);
  }
  lines.push(""); // empty separator line

  // Column headers
  const headerRow = options.columns
    .map((c) => `"${sanitizeCellForSpreadsheet(c.header).replace(/"/g, '""')}"`)
    .join(",");
  lines.push(headerRow);

  // Data rows
  for (const item of options.data) {
    const rowValues = options.columns.map((col) => {
      let rawVal: unknown;
      if (col.transform) {
        rawVal = col.transform(item);
      } else {
        rawVal = item[col.key];
      }

      if (col.format === "currency" && typeof rawVal === "number") {
        return `"${formatMoney(rawVal)}"`;
      }

      const sanitized = sanitizeCellForSpreadsheet(rawVal);
      return `"${sanitized.replace(/"/g, '""')}"`;
    });
    lines.push(rowValues.join(","));
  }

  // Totals row if provided
  if (options.totalsRow) {
    const totalsValues = options.columns.map((col) => {
      const val = options.totalsRow?.[col.key as string] ?? "";
      if (col.format === "currency" && typeof val === "number") {
        return `"${formatMoney(val)}"`;
      }
      const sanitized = sanitizeCellForSpreadsheet(val);
      return `"${sanitized.replace(/"/g, '""')}"`;
    });
    lines.push(totalsValues.join(","));
  }

  // Prepend UTF-8 Byte Order Mark (BOM) so Excel opens UTF-8 cleanly
  return `\uFEFF${lines.join("\r\n")}`;
}

function pdfSafe(value: unknown): string {
  return String(value ?? "")
    .normalize("NFKD")
    .replace(/[^\x20-\x7E]/g, " ")
    .replace(/\\/g, "\\\\")
    .replace(/\(/g, "\\(")
    .replace(/\)/g, "\\)");
}

/** Generates a small standards-compliant PDF without browser print dialogs. */
export function generatePdfReport<T extends Record<string, unknown>>(
  options: ExportReportOptions<T>,
): Buffer {
  const lines: string[] = [
    `${options.businessName ?? "Nexora"} - ${options.reportTitle}`,
    options.periodLabel ? `Period: ${options.periodLabel}` : "",
    `Generated: ${options.generatedAt ?? new Date().toISOString()}`,
    options.generatedBy ? `Generated by: ${options.generatedBy}` : "",
    "",
    options.columns.map((column) => column.header).join(" | "),
    "-".repeat(96),
  ].filter((line, index) => line || index >= 4);

  for (const row of options.data) {
    lines.push(
      options.columns
        .map((column) => {
          const raw = column.transform ? column.transform(row) : row[column.key];
          if (column.format === "currency" && typeof raw === "number") {
            return `INR ${(raw / 100).toFixed(2)}`;
          }
          return String(raw ?? "");
        })
        .join(" | ")
        .slice(0, 150),
    );
  }

  if (options.totalsRow) {
    lines.push("-".repeat(96));
    lines.push(
      options.columns
        .map((column) => {
          const raw = options.totalsRow?.[column.key as string] ?? "";
          return column.format === "currency" && typeof raw === "number"
            ? `INR ${(raw / 100).toFixed(2)}`
            : String(raw);
        })
        .join(" | ")
        .slice(0, 150),
    );
  }

  if (options.data.length === 0) lines.push("No records found for this reporting period.");

  const pageLines: string[][] = [];
  for (let index = 0; index < lines.length; index += 48) {
    pageLines.push(lines.slice(index, index + 48));
  }

  const objects = new Map<number, string>();
  const pageIds = pageLines.map((_, index) => 4 + index * 2);
  objects.set(1, "<< /Type /Catalog /Pages 2 0 R >>");
  objects.set(2, `<< /Type /Pages /Kids [${pageIds.map((id) => `${id} 0 R`).join(" ")}] /Count ${pageIds.length} >>`);
  objects.set(3, "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>");

  pageLines.forEach((page, index) => {
    const pageId = pageIds[index];
    const contentId = pageId + 1;
    const content = `BT\n/F1 9 Tf\n40 802 Td\n12 TL\n${page.map((line) => `(${pdfSafe(line)}) Tj T*`).join("\n")}\nET`;
    objects.set(pageId, `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 3 0 R >> >> /Contents ${contentId} 0 R >>`);
    objects.set(contentId, `<< /Length ${Buffer.byteLength(content, "ascii")} >>\nstream\n${content}\nendstream`);
  });

  let pdf = "%PDF-1.4\n%Nexora\n";
  const offsets = [0];
  const maxObjectId = Math.max(...objects.keys());
  for (let id = 1; id <= maxObjectId; id += 1) {
    offsets[id] = Buffer.byteLength(pdf, "ascii");
    pdf += `${id} 0 obj\n${objects.get(id) ?? "<<>>"}\nendobj\n`;
  }
  const xrefOffset = Buffer.byteLength(pdf, "ascii");
  pdf += `xref\n0 ${maxObjectId + 1}\n0000000000 65535 f \n`;
  for (let id = 1; id <= maxObjectId; id += 1) {
    pdf += `${String(offsets[id]).padStart(10, "0")} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${maxObjectId + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;
  return Buffer.from(pdf, "ascii");
}

/**
 * Generates an XML-based Excel SpreadsheetML document (.xls / .xlsx compatible).
 * Excel natively opens SpreadsheetML preserving types (Numbers, Dates, Strings).
 */
export function generateExcelSpreadsheetXml<T extends Record<string, unknown>>(
  options: ExportReportOptions<T>,
): string {
  const sanitizeXml = (str: string) =>
    str
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;")
      .replace(/'/g, "&apos;");

  const businessName = sanitizeXml(options.businessName ?? "Nexora");
  const reportTitle = sanitizeXml(options.reportTitle);
  const periodLabel = sanitizeXml(options.periodLabel ?? "");
  const generatedAt = sanitizeXml(options.generatedAt ?? new Date().toISOString());

  let rowsXml = "";

  // Title block
  rowsXml += `<Row><Cell><Data ss:Type="String">${businessName} - ${reportTitle}</Data></Cell></Row>\n`;
  if (periodLabel) {
    rowsXml += `<Row><Cell><Data ss:Type="String">Period: ${periodLabel}</Data></Cell></Row>\n`;
  }
  rowsXml += `<Row><Cell><Data ss:Type="String">Generated: ${generatedAt}</Data></Cell></Row>\n`;
  rowsXml += `<Row></Row>\n`; // Blank row

  // Table header
  rowsXml += `<Row ss:StyleID="HeaderRow">\n`;
  for (const col of options.columns) {
    rowsXml += `<Cell><Data ss:Type="String">${sanitizeXml(col.header)}</Data></Cell>\n`;
  }
  rowsXml += `</Row>\n`;

  // Data rows
  for (const item of options.data) {
    rowsXml += `<Row>\n`;
    for (const col of options.columns) {
      let val: unknown;
      if (col.transform) {
        val = col.transform(item);
      } else {
        val = item[col.key];
      }

      if (typeof val === "number") {
        if (col.format === "currency") {
          // Format as rupees in excel
          rowsXml += `<Cell ss:StyleID="CurrencyCell"><Data ss:Type="Number">${val / 100}</Data></Cell>\n`;
        } else {
          rowsXml += `<Cell><Data ss:Type="Number">${val}</Data></Cell>\n`;
        }
      } else {
        const sanitized = sanitizeCellForSpreadsheet(val);
        rowsXml += `<Cell><Data ss:Type="String">${sanitizeXml(sanitized)}</Data></Cell>\n`;
      }
    }
    rowsXml += `</Row>\n`;
  }

  // Totals row
  if (options.totalsRow) {
    rowsXml += `<Row ss:StyleID="TotalsRow">\n`;
    for (const col of options.columns) {
      const val = options.totalsRow[col.key as string] ?? "";
      if (typeof val === "number") {
        if (col.format === "currency") {
          rowsXml += `<Cell ss:StyleID="CurrencyCell"><Data ss:Type="Number">${val / 100}</Data></Cell>\n`;
        } else {
          rowsXml += `<Cell><Data ss:Type="Number">${val}</Data></Cell>\n`;
        }
      } else {
        rowsXml += `<Cell><Data ss:Type="String">${sanitizeXml(String(val))}</Data></Cell>\n`;
      }
    }
    rowsXml += `</Row>\n`;
  }

  return `<?xml version="1.0" encoding="UTF-8"?>
<?mso-application progid="Excel.Sheet"?>
<Workbook xmlns="urn:schemas-microsoft-com:office:spreadsheet"
 xmlns:o="urn:schemas-microsoft-com:office:office"
 xmlns:x="urn:schemas-microsoft-com:office:excel"
 xmlns:ss="urn:schemas-microsoft-com:office:spreadsheet"
 xmlns:html="http://www.w3.org/TR/REC-html40">
 <Styles>
  <Style ss:ID="Default" ss:Name="Normal">
   <Alignment ss:Vertical="Bottom"/>
   <Font ss:FontName="Calibri" ss:Size="11" ss:Color="#000000"/>
  </Style>
  <Style ss:ID="HeaderRow">
   <Font ss:FontName="Calibri" ss:Size="11" ss:Color="#FFFFFF" ss:Bold="1"/>
   <Interior ss:Color="#1E293B" ss:Pattern="Solid"/>
   <Alignment ss:Vertical="Center"/>
  </Style>
  <Style ss:ID="TotalsRow">
   <Font ss:FontName="Calibri" ss:Size="11" ss:Color="#0F172A" ss:Bold="1"/>
   <Interior ss:Color="#F1F5F9" ss:Pattern="Solid"/>
   <Borders>
    <Border ss:Position="Top" ss:LineStyle="Continuous" ss:Weight="1" ss:Color="#94A3B8"/>
    <Border ss:Position="Bottom" ss:LineStyle="Double" ss:Weight="2" ss:Color="#94A3B8"/>
   </Borders>
  </Style>
  <Style ss:ID="CurrencyCell">
   <NumberFormat ss:Format="₹#,##0.00"/>
  </Style>
 </Styles>
 <Worksheet ss:Name="${sanitizeXml(options.reportTitle.slice(0, 30))}">
  <Table>
   ${rowsXml}
  </Table>
 </Worksheet>
</Workbook>`;
}

/**
 * Generates a clean, styled HTML report template optimized for browser printing to PDF.
 */
export function generatePrintableHtmlReport<T extends Record<string, unknown>>(
  options: ExportReportOptions<T>,
): string {
  const sanitize = (str: unknown) =>
    String(str ?? "")
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;");

  let tableHeaderHtml = "<tr>";
  for (const col of options.columns) {
    const align = col.format === "currency" || col.format === "number" ? "text-right" : "text-left";
    tableHeaderHtml += `<th class="py-2.5 px-3 border-b-2 border-slate-900 font-semibold text-xs text-slate-900 uppercase tracking-wider ${align}">${sanitize(col.header)}</th>`;
  }
  tableHeaderHtml += "</tr>";

  let tableRowsHtml = "";
  for (const item of options.data) {
    tableRowsHtml += "<tr class='border-b border-slate-200 hover:bg-slate-50'>";
    for (const col of options.columns) {
      let val: unknown;
      if (col.transform) {
        val = col.transform(item);
      } else {
        val = item[col.key];
      }

      const align = col.format === "currency" || col.format === "number" ? "text-right" : "text-left";
      const displayVal =
        col.format === "currency" && typeof val === "number"
          ? formatMoney(val)
          : sanitize(val);

      tableRowsHtml += `<td class="py-2 px-3 text-xs text-slate-800 ${align}">${displayVal}</td>`;
    }
    tableRowsHtml += "</tr>";
  }

  let totalsHtml = "";
  if (options.totalsRow) {
    totalsHtml += "<tr class='border-t-2 border-slate-900 font-bold bg-slate-50'>";
    for (const col of options.columns) {
      const val = options.totalsRow[col.key as string] ?? "";
      const align = col.format === "currency" || col.format === "number" ? "text-right" : "text-left";
      const displayVal =
        col.format === "currency" && typeof val === "number"
          ? formatMoney(val)
          : sanitize(val);
      totalsHtml += `<td class="py-2.5 px-3 text-xs text-slate-900 ${align}">${displayVal}</td>`;
    }
    totalsHtml += "</tr>";
  }

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <title>${sanitize(options.reportTitle)} - Nexora</title>
  <style>
    body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; margin: 24px; color: #0f172a; }
    .header { margin-bottom: 24px; border-bottom: 1px solid #cbd5e1; padding-bottom: 12px; }
    .title { font-size: 20px; font-weight: 700; margin: 0; color: #0f172a; }
    .subtitle { font-size: 13px; color: #475569; margin-top: 4px; }
    table { width: 100%; border-collapse: collapse; font-size: 12px; }
    th { background: #f8fafc; border-bottom: 2px solid #0f172a; padding: 8px 12px; font-size: 11px; text-transform: uppercase; letter-spacing: 0.05em; }
    td { padding: 8px 12px; border-bottom: 1px solid #e2e8f0; }
    .text-right { text-align: right; }
    .text-left { text-align: left; }
    .footer { margin-top: 24px; font-size: 11px; color: #94a3b8; text-align: center; }
    @media print {
      body { margin: 0; }
      .no-print { display: none; }
    }
  </style>
</head>
<body>
  <div class="no-print" style="margin-bottom: 16px;">
    <button onclick="window.print()" style="padding: 8px 16px; background: #4f46e5; color: white; border: none; border-radius: 6px; cursor: pointer; font-weight: 600; font-size: 13px;">
      Print / Save as PDF
    </button>
  </div>
  <div class="header">
    <div style="display: flex; justify-content: space-between; align-items: flex-start;">
      <div>
        <h1 class="title">${sanitize(options.businessName ?? "Nexora")} — ${sanitize(options.reportTitle)}</h1>
        <p class="subtitle">Reporting Period: ${sanitize(options.periodLabel ?? "All Time")} · Generated: ${sanitize(options.generatedAt ?? new Date().toLocaleString())}</p>
      </div>
      <div style="text-align: right; font-size: 12px; color: #64748b;">
        <p style="margin: 0;"><strong>Confidential Business Report</strong></p>
        <p style="margin: 2px 0 0 0;">Authorized Personnel Only</p>
      </div>
    </div>
  </div>

  <table>
    <thead>
      ${tableHeaderHtml}
    </thead>
    <tbody>
      ${tableRowsHtml}
    </tbody>
    <tfoot>
      ${totalsHtml}
    </tfoot>
  </table>

  <div class="footer">
    <p>Nexora POS &amp; Business Intelligence · Generated automatically from verified database transactions</p>
  </div>
</body>
</html>`;
}
