export interface ExportColumn<T = Record<string, unknown>> {
  header: string;
  key: keyof T | string;
  format?: "text" | "currency" | "number" | "date";
  transform?: (row: T) => string | number;
}

export interface ExportReportOptions<T = Record<string, unknown>> {
  reportTitle: string;
  businessName?: string;
  periodLabel?: string;
  generatedBy?: string;
  generatedAt?: string;
  columns: ExportColumn<T>[];
  data: T[];
  totalsRow?: Record<string, string | number>;
}

/**
 * Sanitizes cell values to prevent CSV / Spreadsheet formula injection.
 * (Prepends single quote if cell starts with =, +, -, @, tab, or carriage return).
 */
export function sanitizeCellForSpreadsheet(val: unknown): string {
  if (val === null || val === undefined) return "";
  const str = String(val);
  if (/^[=+\-@\t\r]/.test(str)) {
    return `'${str}`;
  }
  return str;
}

/**
 * Generates an RFC-4180 compliant CSV string with UTF-8 BOM.
 */
export function generateCsvExport<T extends Record<string, unknown>>(
  options: ExportReportOptions<T>,
): string {
  const lines: string[] = [];

  // Metadata headers
  lines.push(`"${options.businessName ?? "Nexora"} - ${options.reportTitle}"`);
  if (options.periodLabel) {
    lines.push(`"Reporting Period: ${sanitizeCellForSpreadsheet(options.periodLabel)}"`);
  }
  lines.push(`"Generated At: ${options.generatedAt ?? new Date().toISOString()}"`);
  if (options.generatedBy) {
    lines.push(`"Generated By: ${sanitizeCellForSpreadsheet(options.generatedBy)}"`);
  }
  lines.push(""); // empty separator line

  // Column headers
  const headerRow = options.columns
    .map((c) => `"${sanitizeCellForSpreadsheet(c.header).replace(/"/g, '""')}"`)
    .join(",");
  lines.push(headerRow);

  // Data rows
  for (const item of options.data) {
    const rowValues = options.columns.map((col) => {
      let rawVal: unknown;
      if (col.transform) {
        rawVal = col.transform(item);
      } else {
        rawVal = item[col.key];
      }

      if (col.format === "currency" && typeof rawVal === "number") {
        return `"${formatMoney(rawVal)}"`;
      }

      const sanitized = sanitizeCellForSpreadsheet(rawVal);
      return `"${sanitized.replace(/"/g, '""')}"`;
    });
    lines.push(rowValues.join(","));
  }

  // Totals row if provided
  if (options.totalsRow) {
    const totalsValues = options.columns.map((col) => {
      const val = options.totalsRow?.[col.key as string] ?? "";
      if (col.format === "currency" && typeof val === "number") {
        return `"${formatMoney(val)}"`;
      }
      const sanitized = sanitizeCellForSpreadsheet(val);
      return `"${sanitized.replace(/"/g, '""')}"`;
    });
    lines.push(totalsValues.join(","));
  }

  // Prepend UTF-8 Byte Order Mark (BOM) so Excel opens UTF-8 cleanly
  return `\uFEFF${lines.join("\r\n")}`;
}

function reportCellValue<T extends Record<string, unknown>>(
  row: T | Record<string, string | number>,
  column: ExportColumn<T>,
): string {
  const raw = column.transform && row ? column.transform(row as T) : row[column.key as string];
  if (column.format === "currency" && typeof raw === "number") return formatMoney(raw);
  if (column.format === "number" && typeof raw === "number") return raw.toLocaleString("en-IN");
  return String(raw ?? "");
}

/** Generates an A4 branded, paginated PDF with wrapped tables and embedded Unicode fonts. */
export async function generatePdfReport<T extends Record<string, unknown>>(
  options: ExportReportOptions<T>,
): Promise<Buffer> {
  const landscape = options.columns.length > 6;
  const doc = new PDFDocument({
    size: "A4",
    layout: landscape ? "landscape" : "portrait",
    margins: { top: 94, right: 38, bottom: 48, left: 38 },
    bufferPages: true,
    autoFirstPage: false,
    info: { Title: options.reportTitle, Author: options.businessName ?? "Nexora", Subject: options.periodLabel ?? "Business report" },
  });
  const chunks: Buffer[] = [];
  doc.on("data", (chunk: Buffer) => chunks.push(chunk));
  const completed = new Promise<Buffer>((resolve, reject) => {
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);
  });

  const regularFont = path.join(process.cwd(), "node_modules", "@fontsource", "noto-sans", "files", "noto-sans-latin-400-normal.woff");
  const boldFont = path.join(process.cwd(), "node_modules", "@fontsource", "noto-sans", "files", "noto-sans-latin-700-normal.woff");
  const currencyFont = path.join(process.cwd(), "node_modules", "@fontsource", "noto-sans-devanagari", "files", "noto-sans-devanagari-devanagari-400-normal.woff");
  doc.registerFont("NexoraRegular", regularFont);
  doc.registerFont("NexoraBold", boldFont);
  doc.registerFont("NexoraCurrency", currencyFont);
  doc.font("NexoraRegular");
  const logo = readFileSync(path.join(process.cwd(), "public", "nexora-logo.svg"), "utf8");
  const pageWidth = landscape ? 841.89 : 595.28;
  const left = 38;
  const contentWidth = pageWidth - 76;
  const generatedAt = options.generatedAt ?? new Intl.DateTimeFormat("en-IN", {
    dateStyle: "medium", timeStyle: "short", timeZone: process.env.BUSINESS_TIMEZONE || "Asia/Kolkata",
  }).format(new Date());

  const drawPageHeader = () => {
    doc.save();
    doc.rect(0, 0, doc.page.width, 72).fill("#0f172a");
    SVGtoPDF(doc, logo, left, 16, { width: 40, height: 40 });
    doc.font("NexoraBold").fontSize(16).fillColor("#ffffff").text(options.businessName ?? "Nexora", left + 52, 17, { width: 260 });
    doc.font("NexoraRegular").fontSize(8).fillColor("#c7d2fe").text("STORE & OPERATIONS MANAGEMENT", left + 52, 40, { characterSpacing: 0.8 });
    doc.font("NexoraBold").fontSize(8).fillColor("#ffffff").text("CONFIDENTIAL BUSINESS REPORT", pageWidth - 240, 28, { width: 202, align: "right" });
    doc.restore();
    doc.y = 94;
  };
  doc.addPage();
  drawPageHeader();

  doc.font("NexoraBold").fontSize(20).fillColor("#0f172a").text(options.reportTitle, left, doc.y, { width: contentWidth });
  doc.moveDown(0.35);
  const meta = [
    options.periodLabel ? `Period / as of: ${options.periodLabel}` : "",
    `Generated: ${generatedAt}`,
    options.generatedBy ? `Generated by: ${options.generatedBy}` : "",
  ].filter(Boolean).join("   •   ").replace(/₹/g, "Rs. ");
  doc.font("NexoraRegular").fontSize(8.5).fillColor("#64748b").text(meta, { width: contentWidth });
  doc.moveDown(1.1);

  const numericColumn = options.columns.find((column) => column.format === "currency");
  if (/sales/i.test(options.reportTitle) && numericColumn && options.data.length > 1 && options.data.length <= 40) {
    const values = options.data.map((row) => {
      const raw = numericColumn.transform ? numericColumn.transform(row) : row[numericColumn.key];
      return typeof raw === "number" ? raw : 0;
    });
    const max = Math.max(...values, 0);
    if (max > 0) {
      const chartY = doc.y;
      const chartHeight = 56;
      const gap = 2;
      const barWidth = Math.max(2, (contentWidth - gap * (values.length - 1)) / values.length);
      doc.roundedRect(left, chartY, contentWidth, chartHeight + 20, 5).fillAndStroke("#f8fafc", "#e2e8f0");
      values.forEach((value, index) => {
        const height = Math.max(2, (value / max) * chartHeight);
        doc.rect(left + index * (barWidth + gap), chartY + 8 + chartHeight - height, barWidth, height).fill("#4f46e5");
      });
      doc.font("NexoraRegular").fontSize(7).fillColor("#64748b").text(`Trend based on ${numericColumn.header}; highest day ${formatMoney(max).replace("₹", "Rs. ")}.`, left + 6, chartY + chartHeight + 11, { width: contentWidth - 12 });
      doc.y = chartY + chartHeight + 28;
    }
  }

  const numericCount = options.columns.filter((column) => column.format === "currency" || column.format === "number").length;
  const numericWidth = landscape ? 86 : 78;
  const remainingWidth = contentWidth - numericCount * numericWidth;
  const textCount = Math.max(1, options.columns.length - numericCount);
  const widths = options.columns.map((column) =>
    column.format === "currency" || column.format === "number" ? numericWidth : remainingWidth / textCount,
  );
  const drawCellText = (
    cell: string,
    column: ExportColumn<T>,
    x: number,
    y: number,
    width: number,
    height: number,
    bold = false,
  ) => {
    if (column.format === "currency" && cell.startsWith("₹")) {
      const number = cell.slice(1);
      doc.fontSize(7.5);
      doc.font(bold ? "NexoraBold" : "NexoraRegular");
      const numberWidth = doc.widthOfString(number);
      doc.font("NexoraCurrency");
      const symbolWidth = doc.widthOfString("₹");
      const start = x + width - 5 - numberWidth - symbolWidth - 1.5;
      doc.text("₹", start, y + 6, { width: symbolWidth + 1, height: height - 8, lineBreak: false });
      doc.font(bold ? "NexoraBold" : "NexoraRegular").text(number, start + symbolWidth + 1.5, y + 6, { width: numberWidth + 1, height: height - 8, lineBreak: false });
      return;
    }
    doc.font(bold ? "NexoraBold" : "NexoraRegular").fontSize(7.5).text(cell.replace(/₹/g, "Rs. "), x + 5, y + 6, {
      width: width - 10,
      height: height - 8,
      align: column.format === "currency" || column.format === "number" ? "right" : "left",
      lineGap: 1,
    });
  };
  const rowBottom = () => doc.page.height - doc.page.margins.bottom - 14;
  const drawTableHeader = () => {
    const y = doc.y;
    doc.rect(left, y, contentWidth, 24).fill("#312e81");
    let x = left;
    options.columns.forEach((column, index) => {
      const align = column.format === "currency" || column.format === "number" ? "right" : "left";
      doc.font("NexoraBold").fontSize(7).fillColor("#ffffff").text(column.header.toUpperCase(), x + 5, y + 7, { width: widths[index] - 10, align, ellipsis: false });
      x += widths[index];
    });
    doc.y = y + 24;
  };
  const ensureSpace = (height: number) => {
    if (doc.y + height <= rowBottom()) return;
    doc.addPage();
    drawPageHeader();
    drawTableHeader();
  };
  drawTableHeader();

  if (options.data.length === 0) {
    doc.font("NexoraRegular").fontSize(9).fillColor("#64748b").text("No verified records were found for this reporting period.", left + 8, doc.y + 12, { width: contentWidth - 16, align: "center" });
    doc.y += 40;
  } else {
    options.data.forEach((row, rowIndex) => {
      const cells = options.columns.map((column) => reportCellValue(row, column));
      doc.font("NexoraRegular").fontSize(7.5);
      const rowHeight = Math.max(24, ...cells.map((cell, index) => doc.heightOfString(cell, { width: widths[index] - 10, lineGap: 1 }) + 10));
      ensureSpace(rowHeight);
      const y = doc.y;
      if (rowIndex % 2 === 1) doc.rect(left, y, contentWidth, rowHeight).fill("#f8fafc");
      let x = left;
      cells.forEach((cell, index) => {
        const column = options.columns[index];
        doc.fillColor("#1e293b");
        drawCellText(cell, column, x, y, widths[index], rowHeight);
        x += widths[index];
      });
      doc.moveTo(left, y + rowHeight).lineTo(left + contentWidth, y + rowHeight).strokeColor("#e2e8f0").lineWidth(0.5).stroke();
      doc.y = y + rowHeight;
    });
  }

  if (options.totalsRow) {
    const cells = options.columns.map((column) => reportCellValue(options.totalsRow!, column));
    doc.font("NexoraBold").fontSize(7.5);
    const height = Math.max(26, ...cells.map((cell, index) => doc.heightOfString(cell, { width: widths[index] - 10 }) + 10));
    ensureSpace(height);
    const y = doc.y;
    doc.rect(left, y, contentWidth, height).fill("#eef2ff");
    let x = left;
    cells.forEach((cell, index) => {
      const column = options.columns[index];
      doc.fillColor("#1e1b4b");
      drawCellText(cell, column, x, y + 1, widths[index], height, true);
      x += widths[index];
    });
    doc.y = y + height;
  }

  const range = doc.bufferedPageRange();
  for (let pageIndex = range.start; pageIndex < range.start + range.count; pageIndex += 1) {
    doc.switchToPage(pageIndex);
    const footerY = doc.page.height - doc.page.margins.bottom - 10;
    doc.moveTo(left, footerY - 6).lineTo(doc.page.width - doc.page.margins.right, footerY - 6).strokeColor("#cbd5e1").lineWidth(0.5).stroke();
    doc.font("NexoraRegular").fontSize(7).fillColor("#64748b").text("Nexora POS • Generated from verified database records", left, footerY, { width: contentWidth - 80, height: 9, lineBreak: false });
    doc.text(`Page ${pageIndex - range.start + 1} of ${range.count}`, doc.page.width - doc.page.margins.right - 80, footerY, { width: 80, height: 9, align: "right", lineBreak: false });
  }
  doc.end();
  return completed;
}

/**
 * Generates an XML-based Excel SpreadsheetML document (.xls / .xlsx compatible).
 * Excel natively opens SpreadsheetML preserving types (Numbers, Dates, Strings).
 */
export function generateExcelSpreadsheetXml<T extends Record<string, unknown>>(
  options: ExportReportOptions<T>,
): string {
  const sanitizeXml = (str: string) =>
    str
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;")
      .replace(/'/g, "&apos;");

  const businessName = sanitizeXml(options.businessName ?? "Nexora");
  const reportTitle = sanitizeXml(options.reportTitle);
  const periodLabel = sanitizeXml(options.periodLabel ?? "");
  const generatedAt = sanitizeXml(options.generatedAt ?? new Date().toISOString());

  let rowsXml = "";

  // Title block
  rowsXml += `<Row><Cell><Data ss:Type="String">${businessName} - ${reportTitle}</Data></Cell></Row>\n`;
  if (periodLabel) {
    rowsXml += `<Row><Cell><Data ss:Type="String">Period: ${periodLabel}</Data></Cell></Row>\n`;
  }
  rowsXml += `<Row><Cell><Data ss:Type="String">Generated: ${generatedAt}</Data></Cell></Row>\n`;
  rowsXml += `<Row></Row>\n`; // Blank row

  // Table header
  rowsXml += `<Row ss:StyleID="HeaderRow">\n`;
  for (const col of options.columns) {
    rowsXml += `<Cell><Data ss:Type="String">${sanitizeXml(col.header)}</Data></Cell>\n`;
  }
  rowsXml += `</Row>\n`;

  // Data rows
  for (const item of options.data) {
    rowsXml += `<Row>\n`;
    for (const col of options.columns) {
      let val: unknown;
      if (col.transform) {
        val = col.transform(item);
      } else {
        val = item[col.key];
      }

      if (typeof val === "number") {
        if (col.format === "currency") {
          // Format as rupees in excel
          rowsXml += `<Cell ss:StyleID="CurrencyCell"><Data ss:Type="Number">${val / 100}</Data></Cell>\n`;
        } else {
          rowsXml += `<Cell><Data ss:Type="Number">${val}</Data></Cell>\n`;
        }
      } else {
        const sanitized = sanitizeCellForSpreadsheet(val);
        rowsXml += `<Cell><Data ss:Type="String">${sanitizeXml(sanitized)}</Data></Cell>\n`;
      }
    }
    rowsXml += `</Row>\n`;
  }

  // Totals row
  if (options.totalsRow) {
    rowsXml += `<Row ss:StyleID="TotalsRow">\n`;
    for (const col of options.columns) {
      const val = options.totalsRow[col.key as string] ?? "";
      if (typeof val === "number") {
        if (col.format === "currency") {
          rowsXml += `<Cell ss:StyleID="CurrencyCell"><Data ss:Type="Number">${val / 100}</Data></Cell>\n`;
        } else {
          rowsXml += `<Cell><Data ss:Type="Number">${val}</Data></Cell>\n`;
        }
      } else {
        rowsXml += `<Cell><Data ss:Type="String">${sanitizeXml(String(val))}</Data></Cell>\n`;
      }
    }
    rowsXml += `</Row>\n`;
  }

  return `<?xml version="1.0" encoding="UTF-8"?>
<?mso-application progid="Excel.Sheet"?>
<Workbook xmlns="urn:schemas-microsoft-com:office:spreadsheet"
 xmlns:o="urn:schemas-microsoft-com:office:office"
 xmlns:x="urn:schemas-microsoft-com:office:excel"
 xmlns:ss="urn:schemas-microsoft-com:office:spreadsheet"
 xmlns:html="http://www.w3.org/TR/REC-html40">
 <Styles>
  <Style ss:ID="Default" ss:Name="Normal">
   <Alignment ss:Vertical="Bottom"/>
   <Font ss:FontName="Calibri" ss:Size="11" ss:Color="#000000"/>
  </Style>
  <Style ss:ID="HeaderRow">
   <Font ss:FontName="Calibri" ss:Size="11" ss:Color="#FFFFFF" ss:Bold="1"/>
   <Interior ss:Color="#1E293B" ss:Pattern="Solid"/>
   <Alignment ss:Vertical="Center"/>
  </Style>
  <Style ss:ID="TotalsRow">
   <Font ss:FontName="Calibri" ss:Size="11" ss:Color="#0F172A" ss:Bold="1"/>
   <Interior ss:Color="#F1F5F9" ss:Pattern="Solid"/>
   <Borders>
    <Border ss:Position="Top" ss:LineStyle="Continuous" ss:Weight="1" ss:Color="#94A3B8"/>
    <Border ss:Position="Bottom" ss:LineStyle="Double" ss:Weight="2" ss:Color="#94A3B8"/>
   </Borders>
  </Style>
  <Style ss:ID="CurrencyCell">
   <NumberFormat ss:Format="₹#,##0.00"/>
  </Style>
 </Styles>
 <Worksheet ss:Name="${sanitizeXml(options.reportTitle.slice(0, 30))}">
  <Table>
   ${rowsXml}
  </Table>
 </Worksheet>
</Workbook>`;
}

/**
 * Generates a clean, styled HTML report template optimized for browser printing to PDF.
 */
export function generatePrintableHtmlReport<T extends Record<string, unknown>>(
  options: ExportReportOptions<T>,
): string {
  const sanitize = (str: unknown) =>
    String(str ?? "")
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;");

  let tableHeaderHtml = "<tr>";
  for (const col of options.columns) {
    const align = col.format === "currency" || col.format === "number" ? "text-right" : "text-left";
    tableHeaderHtml += `<th class="py-2.5 px-3 border-b-2 border-slate-900 font-semibold text-xs text-slate-900 uppercase tracking-wider ${align}">${sanitize(col.header)}</th>`;
  }
  tableHeaderHtml += "</tr>";

  let tableRowsHtml = "";
  for (const item of options.data) {
    tableRowsHtml += "<tr class='border-b border-slate-200 hover:bg-slate-50'>";
    for (const col of options.columns) {
      let val: unknown;
      if (col.transform) {
        val = col.transform(item);
      } else {
        val = item[col.key];
      }

      const align = col.format === "currency" || col.format === "number" ? "text-right" : "text-left";
      const displayVal =
        col.format === "currency" && typeof val === "number"
          ? formatMoney(val)
          : sanitize(val);

      tableRowsHtml += `<td class="py-2 px-3 text-xs text-slate-800 ${align}">${displayVal}</td>`;
    }
    tableRowsHtml += "</tr>";
  }

  let totalsHtml = "";
  if (options.totalsRow) {
    totalsHtml += "<tr class='border-t-2 border-slate-900 font-bold bg-slate-50'>";
    for (const col of options.columns) {
      const val = options.totalsRow[col.key as string] ?? "";
      const align = col.format === "currency" || col.format === "number" ? "text-right" : "text-left";
      const displayVal =
        col.format === "currency" && typeof val === "number"
          ? formatMoney(val)
          : sanitize(val);
      totalsHtml += `<td class="py-2.5 px-3 text-xs text-slate-900 ${align}">${displayVal}</td>`;
    }
    totalsHtml += "</tr>";
  }

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <title>${sanitize(options.reportTitle)} - Nexora</title>
  <style>
    body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; margin: 24px; color: #0f172a; }
    .header { margin-bottom: 24px; border-bottom: 1px solid #cbd5e1; padding-bottom: 12px; }
    .title { font-size: 20px; font-weight: 700; margin: 0; color: #0f172a; }
    .subtitle { font-size: 13px; color: #475569; margin-top: 4px; }
    table { width: 100%; border-collapse: collapse; font-size: 12px; }
    th { background: #f8fafc; border-bottom: 2px solid #0f172a; padding: 8px 12px; font-size: 11px; text-transform: uppercase; letter-spacing: 0.05em; }
    td { padding: 8px 12px; border-bottom: 1px solid #e2e8f0; }
    .text-right { text-align: right; }
    .text-left { text-align: left; }
    .footer { margin-top: 24px; font-size: 11px; color: #94a3b8; text-align: center; }
    @media print {
      body { margin: 0; }
      .no-print { display: none; }
    }
  </style>
</head>
<body>
  <div class="no-print" style="margin-bottom: 16px;">
    <button onclick="window.print()" style="padding: 8px 16px; background: #4f46e5; color: white; border: none; border-radius: 6px; cursor: pointer; font-weight: 600; font-size: 13px;">
      Print / Save as PDF
    </button>
  </div>
  <div class="header">
    <div style="display: flex; justify-content: space-between; align-items: flex-start;">
      <div>
        <h1 class="title">${sanitize(options.businessName ?? "Nexora")} — ${sanitize(options.reportTitle)}</h1>
        <p class="subtitle">Reporting Period: ${sanitize(options.periodLabel ?? "All Time")} · Generated: ${sanitize(options.generatedAt ?? new Date().toLocaleString())}</p>
      </div>
      <div style="text-align: right; font-size: 12px; color: #64748b;">
        <p style="margin: 0;"><strong>Confidential Business Report</strong></p>
        <p style="margin: 2px 0 0 0;">Authorized Personnel Only</p>
      </div>
    </div>
  </div>

  <table>
    <thead>
      ${tableHeaderHtml}
    </thead>
    <tbody>
      ${tableRowsHtml}
    </tbody>
    <tfoot>
      ${totalsHtml}
    </tfoot>
  </table>

  <div class="footer">
    <p>Nexora POS &amp; Business Intelligence · Generated automatically from verified database transactions</p>
  </div>
</body>
</html>`;
}
